function closest(value: number, choices: readonly string[]): string {
  const red = value >> 16 & 255, green = value >> 8 & 255, blue = value & 255;
  let best = choices[0], distance = Infinity;
  for (const hex of choices) {
    const rgb = Number.parseInt(hex.slice(1), 16);
    const score = 2 * (red - (rgb >> 16 & 255)) ** 2 + 3 * (green - (rgb >> 8 & 255)) ** 2 + (blue - (rgb & 255)) ** 2;
    if (score < distance) { best = hex; distance = score; }
  }
  return best;
}
const knownColours = [...new Set([...Object.values(palette).flatMap(Object.values), ...Object.values(materials), ...Object.values(pigments).flat()])];
export function nearestSample(hex: string) { return closest(Number.parseInt(hex.replace('#', ''), 16), knownColours); }
export function residentColors(appearance: Resident['appearance']) {
  return { hair: closest(appearance.hair, pigments.hair), shirt: closest(appearance.shirt, pigments.shirt), skin: closest(appearance.skin, pigments.skin) };
}
